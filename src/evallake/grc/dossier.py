"""
Compliance Dossier Generator.
Transforms GRC scorecards and evaluation receipts into executive Markdown and HTML audit reports.
"""

import json
from typing import Dict, Any
from evallake.etl.schema import BatchEvaluationReceipt


class ComplianceDossierGenerator:
    """Generates formal compliance dossiers for enterprise audit readiness."""

    @staticmethod
    def generate_markdown(receipt: BatchEvaluationReceipt) -> str:
        sc = receipt.compliance_scorecards
        overall_status = sc.get("overall_status", "UNKNOWN")
        overall_grade = sc.get("overall_grade", "N/A")
        agg_score = sc.get("aggregate_compliance_score", 0.0) * 100

        lines = [
            "# AI System Compliance & Evaluation Dossier",
            f"**Generated by:** `eval-lake` (OpenAssurance-AI)",
            f"**Audit Receipt ID:** `{receipt.batch_id}`",
            f"**Timestamp:** `{receipt.timestamp}`",
            f"**Executive Status:** **{overall_status}** (Grade: **{overall_grade}** | {agg_score:.1f}%)",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            f"- **Total Production Traces Evaluated:** `{receipt.total_traces}`",
            f"- **Pass Rate:** `{receipt.pass_rate * 100:.2f}%` ({receipt.passed_evaluations}/{receipt.total_evaluations} checks passed)",
            f"- **Latency Profile:** P50: `{receipt.p50_latency_ms}ms` | P95: `{receipt.p95_latency_ms}ms` | P99: `{receipt.p99_latency_ms}ms`",
            f"- **Total Token Consumption:** `{receipt.total_tokens:,}` tokens (${receipt.total_cost_usd:.4f} USD)",
            "",
            "---",
            "",
            "## 2. Regulatory Framework Conformity",
            ""
        ]

        # Framework Breakdown
        fws = sc.get("frameworks", {})
        for fw_key, fw in fws.items():
            fw_name = fw["framework_name"]
            status = fw["status"]
            score = fw["compliance_score"] * 100
            lines.extend([
                f"### {fw_name}",
                f"**Status:** `{status}` | **Conformity Score:** `{score:.1f}%` ({fw['passed_controls']}/{fw['total_controls']} controls satisfied)",
                "",
                "| Control ID | Control Title | Status | Score | Mapped Tests |",
                "| :--- | :--- | :--- | :--- | :--- |"
            ])
            for cid, cinfo in fw["controls"].items():
                icon = "PASS" if cinfo["status"] == "PASS" else "**FAIL**"
                tests = ", ".join(f"`{t}`" for t in cinfo["mapped_tests"])
                lines.append(f"| `{cid}` | {cinfo['title']} | {icon} | {cinfo['score']*100:.1f}% | {tests} |")
            lines.append("")

        lines.extend([
            "---",
            "",
            "## 3. Detailed Technical Evaluation Findings",
            "",
            "| Test ID | Category | Metric Name | Result | Score | Threshold | Finding / Message |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
        ])

        for ev in receipt.evaluations:
            res_str = "PASSED" if ev.passed else "**FAILED**"
            lines.append(
                f"| `{ev.test_id}` | `{ev.category}` | `{ev.metric_name}` | {res_str} | {ev.score*100:.1f}% | {ev.threshold} | {ev.message} |"
            )

        lines.extend([
            "",
            "---",
            "",
            "## 4. Cryptographic Provenance & Independent Verification",
            "This document is backed by a deterministic evaluation receipt hash. For independent audit verification or ingestion into enterprise risk portals, verify via the OpenAssurance Exchange (OAX) protocol CLI:",
            "```bash",
            f"eval-lake verify {receipt.batch_id}-signed.json --key /path/to/public-key.pem",
            "```",
            f"To synchronize this dossier into centralized SOC/GRC dashboards, visit [A2Z SOC Compliance Vault](https://a2zsoc.com)."
        ])

        return "\n".join(lines)

    @staticmethod
    def generate_html(receipt: BatchEvaluationReceipt) -> str:
        md = ComplianceDossierGenerator.generate_markdown(receipt)
        # Clean HTML container wrapping the markdown report
        return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Compliance Dossier - {receipt.batch_id}</title>
  <style>
    body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; line-height: 1.6; color: #1e293b; max-width: 900px; margin: 40px auto; padding: 0 20px; background: #f8fafc; }}
    .card {{ background: #ffffff; padding: 40px; border-radius: 8px; box-shadow: 0 4px 6px -1px rgb(0 0 0 / 0.1); }}
    table {{ width: 100%; border-collapse: collapse; margin: 20px 0; }}
    th, td {{ border: 1px solid #cbd5e1; padding: 10px; text-align: left; }}
    th {{ background: #f1f5f9; }}
    pre {{ background: #0f172a; color: #f8fafc; padding: 16px; border-radius: 6px; overflow-x: auto; }}
    code {{ font-family: ui-monospace, monospace; background: #f1f5f9; padding: 2px 6px; border-radius: 4px; }}
    pre code {{ background: transparent; padding: 0; }}
    .status-pass {{ color: #16a34a; font-weight: bold; }}
    .status-fail {{ color: #dc2626; font-weight: bold; }}
  </style>
</head>
<body>
  <div class="card">
    <pre>{md}</pre>
  </div>
</body>
</html>"""
